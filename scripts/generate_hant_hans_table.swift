// Generate shared/nav_ui/src/moto_hant_hans_table.h: the Traditional Chinese
// characters the round screen's text face cannot draw, each paired with the
// one Simplified character that it can.
//
// The text face (scripts/generate_fonts.sh) carries GB2312's 6,763 hanzi, so a
// Traditional title such as 張學友 used to lose every character GB2312 spells
// differently. The music labels look a missing glyph up here before giving up
// on it, which keeps the rider's library readable without shipping a second
// set of glyphs.
//
// Source: ICU's "Hant-Hans" transliterator, reached through Foundation. Its
// rules are CLDR's common/transforms/Simplified-Traditional.xml run backward;
// both are Unicode data under the Unicode License v3 (LICENSES/Unicode-3.0.txt,
// THIRD_PARTY_NOTICES.md). Only pairs that map one codepoint to exactly one
// codepoint are kept; the label never gets a phrase-level rewrite, only a
// missing glyph replaced.
//
// The hanzi set must stay the one generate_fonts.sh feeds lv_font_conv: GB2312
// rows 0xB0-0xF7. Change one and regenerate the other.
//
// Usage: swift scripts/generate_hant_hans_table.swift
//        (writes the header next to the code that includes it)

import Foundation

let repo = URL(fileURLWithPath: #filePath).deletingLastPathComponent()
    .deletingLastPathComponent()
let output = repo.appendingPathComponent(
    "shared/nav_ui/src/moto_hant_hans_table.h")

// GB2312 as EUC-CN, the same byte layout Python's "gb2312" codec decodes in
// generate_fonts.sh. Rows 0xB0-0xD7 are level 1, 0xD8-0xF7 level 2.
let euc = String.Encoding(rawValue: CFStringConvertEncodingToNSStringEncoding(
    CFStringEncoding(CFStringEncodings.EUC_CN.rawValue)))
var hanzi = Set<UInt32>()
for high in 0xB0...0xF7 {
    for low in 0xA1...0xFE {
        guard let text = String(data: Data([UInt8(high), UInt8(low)]),
                                encoding: euc),
              text.unicodeScalars.count == 1 else { continue }
        hanzi.insert(text.unicodeScalars.first!.value)
    }
}
// A different count means the codec disagrees with the font build, and the
// table would promise glyphs the face does not have.
guard hanzi.count == 6763 else {
    FileHandle.standardError.write(
        "GB2312 decoded to \(hanzi.count) hanzi, expected 6763\n".data(using: .utf8)!)
    exit(1)
}

let transform = StringTransform("Hant-Hans")
var pairs: [(UInt32, UInt32)] = []
// CJK Unified Ideographs Extension A, then the main block. Both stay in the
// BMP, so either side of a pair fits 16 bits.
for range in [0x3400...0x4DBF, 0x4E00...0x9FFF] {
    for value in range {
        let source = UInt32(value)
        if hanzi.contains(source) { continue }
        guard let scalar = Unicode.Scalar(source),
              let simplified = String(Character(scalar))
                  .applyingTransform(transform, reverse: false) else { continue }
        let scalars = Array(simplified.unicodeScalars)
        guard scalars.count == 1, scalars[0].value != source,
              hanzi.contains(scalars[0].value) else { continue }
        pairs.append((source, scalars[0].value))
    }
}

// The versions behind this run, so a regenerated table that differs can be
// traced to a newer ICU rather than to an edit.
func icuVersion(_ symbol: String) -> String {
    guard let library = dlopen("/usr/lib/libicucore.dylib", RTLD_NOW),
          let address = dlsym(library, symbol) else { return "unknown" }
    var version = [UInt8](repeating: 0, count: 4)
    if symbol == "ulocdata_getCLDRVersion" {
        typealias Getter = @convention(c) (UnsafeMutablePointer<UInt8>,
                                           UnsafeMutablePointer<Int32>) -> Void
        var status: Int32 = 0
        unsafeBitCast(address, to: Getter.self)(&version, &status)
    } else {
        typealias Getter = @convention(c) (UnsafeMutablePointer<UInt8>) -> Void
        unsafeBitCast(address, to: Getter.self)(&version)
    }
    var parts = version.map(String.init)
    while parts.count > 2, parts.last == "0" { parts.removeLast() }
    return parts.joined(separator: ".")
}

func hex(_ value: UInt32) -> String {
    "0x" + String(value, radix: 16, uppercase: true)
}

var text = """
// Generated by scripts/generate_hant_hans_table.swift; do not edit by hand.
// Regenerate: swift scripts/generate_hant_hans_table.swift
//
// Traditional -> Simplified pairs for the hanzi the text face cannot draw.
// Each source is a CJK Unified Ideograph (or Extension A) outside GB2312 rows
// 0xB0-0xF7, the set scripts/generate_fonts.sh subsets the text face to; each
// target is exactly one codepoint inside it. Sorted by source for a binary
// search. \(pairs.count) pairs, \(pairs.count * 4) bytes.
//
// Data: ICU's "Hant-Hans" transliterator, i.e. CLDR's
// common/transforms/Simplified-Traditional.xml run backward; generated with
// ICU \(icuVersion("u_getVersion")) / CLDR \(icuVersion("ulocdata_getCLDRVersion")) as shipped in macOS Foundation. Unicode, Inc. data
// under the Unicode License v3 (LICENSES/Unicode-3.0.txt).

#pragma once

#include <cstdint>

namespace moto::nav_ui::detail {

struct HantHansPair {
    std::uint16_t traditional;
    std::uint16_t simplified;
};

// One definition shared by every translation unit that includes this.
inline constexpr HantHansPair kHantHans[] = {

"""
let perLine = 4
for start in stride(from: 0, to: pairs.count, by: perLine) {
    let line = pairs[start..<min(start + perLine, pairs.count)]
        .map { "{\(hex($0.0)), \(hex($0.1))}," }
        .joined(separator: " ")
    text += "    \(line)\n"
}
text += """
};

}  // namespace moto::nav_ui::detail

"""

try text.write(to: output, atomically: true, encoding: .utf8)
print("wrote \(output.path): \(pairs.count) pairs, \(pairs.count * 4) bytes")
